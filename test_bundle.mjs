import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import crypto from 'node:crypto';
import {execFileSync} from 'node:child_process';
import {fileURLToPath} from 'node:url';

const script = path.join(path.dirname(fileURLToPath(import.meta.url)), 'bundle_crypto.mjs');
const root = fs.mkdtempSync(path.join(os.tmpdir(), 'nya-bundle-check-'));
const key = crypto.randomBytes(32);
const env = {...process.env, NYA_3D_BUNDLE_KEY_B64:key.toString('base64')};
const run = (...args) => execFileSync(process.execPath, [script, ...args], {env,stdio:'pipe'});
fs.mkdirSync(path.join(root,'in'));
fs.writeFileSync(path.join(root,'in','入力.txt'),'入力と生成物の秘密保持を確認');
run('pack',path.join(root,'in'),path.join(root,'bundle.bin'));
run('unpack',path.join(root,'bundle.bin'),path.join(root,'out'));
assert.equal(fs.readFileSync(path.join(root,'out','入力.txt'),'utf8'),'入力と生成物の秘密保持を確認');
assert.throws(()=>run('unpack',path.join(root,'bundle.bin'),path.join(root,'out')));
const bad=fs.readFileSync(path.join(root,'bundle.bin'));bad[bad.length-1]^=1;
fs.writeFileSync(path.join(root,'broken.bin'),bad);
assert.throws(()=>run('unpack',path.join(root,'broken.bin'),path.join(root,'bad-out')));
assert.equal(fs.existsSync(path.join(root,'bad-out')),false);
const nonce=crypto.randomBytes(12), cipher=crypto.createCipheriv('aes-256-gcm',key,nonce);
cipher.setAAD(Buffer.from('harbour-nya-3d-bundle-v1'));
const bytes=Buffer.from('範囲外へ書き込まない');
const payload=Buffer.from(JSON.stringify({version:1,files:[{name:'../outside.txt',size:bytes.length,sha256:crypto.createHash('sha256').update(bytes).digest('hex'),data:bytes.toString('base64')}]}));
const encrypted=Buffer.concat([cipher.update(payload),cipher.final()]);
fs.writeFileSync(path.join(root,'traversal.bin'),Buffer.concat([Buffer.from('NYA3D01'),nonce,cipher.getAuthTag(),encrypted]));
assert.throws(()=>run('unpack',path.join(root,'traversal.bin'),path.join(root,'traversal-out')));
assert.equal(fs.existsSync(path.join(root,'outside.txt')),false);
console.log('暗号化復元・改ざん拒否・上書き拒否・保存範囲の検証に合格しました。');
